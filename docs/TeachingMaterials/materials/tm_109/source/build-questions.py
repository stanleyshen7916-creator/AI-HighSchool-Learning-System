def build(mid, items):
    qs = []
    for i, it in enumerate(items, 1):
        rng = random.Random("%s-%d" % (mid, i))
        if it["letters"]:
            opts = ["(%s) %s" % (L[k], o) for k, o in enumerate(it["opts"])]
            ans = "".join("(%s)" % c for c in it["letters"])
        else:
            opts = list(it["opts"])
            ans = opts[0]
            rng.shuffle(opts)
        ref = REF_GPT % (it["page"], it["gpt"]) if it["gpt"] else REF % it["page"]
        qs.append(dict(questionId="%s_q%d" % (mid, i), materialId=mid, questionNumber=str(i), type="single_choice",
                       questionSource="AI_GENERATED", origin="AI", question=it["stem"], options=opts, answer=ans,
                       explanation="（題目為 AI 依課本內容命題）課本 p.%d：%s" % (it["page"], it["expl"]),
                       page=it["page"], section=it["section"], version="1", createdDate=DATE,
                       knowledgePoint=it["kp"], difficulty=it["diff"], reference=ref))
    out = os.path.join(ROOT, "docs/TeachingMaterials/materials", mid, "questionbank.json")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(dict(materialId=mid, questions=qs), f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(mid, len(qs), "questions,", sum(1 for q in items if q["letters"]), "multi,",
          sum(1 for q in items if q["gpt"]), "adapted from GPT")


