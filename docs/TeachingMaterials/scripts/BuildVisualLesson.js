/* docs/TeachingMaterials/scripts/BuildVisualLesson.js — 圖解教材產生器.

   每份圖解教材的內容寫在 docs/TeachingMaterials/lessons/src/<lessonId>.js（CommonJS
   spec：章節、卡片六段內容、題目、互動圖的程式），本腳本把它組成一份完整的
   lessons/<lessonId>.html（載入 shared/ 的 boot／runtime／css），版面與數學第1章相同。

   Run: node docs/TeachingMaterials/scripts/BuildVisualLesson.js [lessonId ...]   （不帶參數＝全部）
        --check  只檢查輸出是否與 spec 一致（給測試用），不寫檔

   Spec 格式（每個欄位的 HTML 都是作者寫好的內容，產生器只負責組版）：
   {
     lessonId, title, eyebrow, h1, h1small, subject, unit, legend: ["src","add"],
     sections: [{ id, short, title, plan: { goal, prereq, time }, cards: [card...] }],
     footer: ["<li> 內容 html", ...],
     script: "這份教材自己的互動圖（呼叫 widget(...)）"
   }
   card = { id:"F1", title, page, tags:["src"|"add"], say, formula,
            widget: { id, aria, rw, controls:[{ k, label, min, max, step }], play:{ k, dur } },
            space, trap,
            quiz: { q, answer:"b" | "a,c", multi, options:[{ c, text, why }] },
            sol: { id, aria, controls?:[...], onlyStep? } } */
"use strict";
const fs = require("fs");
const path = require("path");

const LESSONS = path.join(__dirname, "..", "lessons");
const TAG = { src: '<span class="tag src">依上傳教材</span>', add: '<span class="tag add">老師補充</span>' };

function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;"); }

function slider(wid, c) {
  return '<label class="sl"' + (c.onlyStep != null ? ' data-only-step="' + c.onlyStep + '"' : "") + '><span>' + c.label + '</span><input type="range" id="' + wid + "-" + c.k +
    '" data-k="' + c.k + '" min="' + c.min + '" max="' + c.max + '" step="' + c.step + '"><output data-v="' + c.k + '"></output></label>';
}

function card(spec, sec, c, n) {
  const w = c.widget, q = c.quiz;
  const ctl = (w.controls || []).map((x) => "          " + slider(w.id, x)).join("\n") +
    (w.play ? '\n          <button class="play" type="button" data-play="' + w.play.k + '" data-dur="' + (w.play.dur || 4000) + '">▶ 播放</button>' : "") +
    (w.extra ? "\n          " + w.extra : "");
  const opts = q.options.map((o) => '          <button type="button" data-c="' + o.c + '"' + (q.multi ? ' aria-pressed="false"' : "") +
    (o.why ? ' data-why="' + esc(o.why) + '"' : "") + ">" + o.text + "</button>").join("\n");
  const solCtl = (c.sol.controls || []).map((x) => slider(c.sol.id, x)).join("");
  return `
    <!-- ${c.id} -->
    <article class="card" id="${c.id}" data-ahs-formula="${spec.unit}-${sec.id}-${c.id}" data-ahs-source="${esc(c.page || "")}">
      <div class="card-h"><span class="code">${sec.id} · ${c.id}</span><h3>${c.title}</h3>${c.page ? '<span class="pg">' + c.page + "</span>" : ""}${(c.tags || ["src"]).map((t) => TAG[t]).join("")}</div>
      <div class="say"><span class="who">老師說</span><p>${c.say}</p></div>
      <div class="formula">${c.formula}</div>
      <div class="viz" id="${w.id}">
        <div class="cv"><canvas aria-label="${esc(w.aria)}"></canvas></div>
        <div class="ctl">
${ctl}
        </div>
        <p class="out" data-out></p>
      </div>
      <div class="notes">
        <div class="space"><b>空間感</b>${c.space}</div>
        <div class="trap"><b>常見錯誤</b>${c.trap}</div>
      </div>
      <div class="qc" data-q="${c.id}">
        <p class="q"><b>小試身手</b>${q.q}</p>
        <div class="choices" data-answer="${q.answer}"${q.multi ? " data-multi" : ""}>
${opts}
        </div>${q.multi ? '\n        <button class="check" type="button" data-check>檢查</button>' : ""}
        <p class="fb" aria-live="polite"></p>
        <details class="sol"><summary>看圖解（先自己想想再打開）</summary>
          <div class="viz" id="${c.sol.id}"><div class="cv"><canvas aria-label="${esc(c.sol.aria)}"></canvas></div>
            <div class="ctl"><button class="play" type="button" data-step="-1">◀ 上一步</button><button class="play" type="button" data-step="1">下一步 ▶</button><span class="stepno" data-stepno></span>${solCtl}</div>
            <p class="out" data-out></p></div>
        </details>
      </div>
      <label class="done"><input type="checkbox" id="done-${c.id}" data-done="${c.id}">我會了</label>
    </article>`;
}

function build(spec) {
  let n = 0;
  spec.sections.forEach((s) => { n += s.cards.length; });
  const sections = spec.sections.map((s) => `
  <section id="s${s.id}">
    <h2><span class="no">${s.id}</span>${s.title}</h2>
    <div class="plan">
      <div><b>本節目標</b>${s.plan.goal}</div>
      <div><b>先備知識</b>${s.plan.prereq}</div>
      <div><b>建議節數</b>${s.plan.time}</div>
    </div>
${s.cards.map((c) => card(spec, s, c)).join("\n")}
  </section>`).join("\n");
  return `<!doctype html>
<html lang="zh-Hant">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${spec.title}</title>
<!-- GENERATED by docs/TeachingMaterials/scripts/BuildVisualLesson.js from lessons/src/${spec.lessonId}.js — 請改 src 後重新產生，不要直接改這個檔。 -->
<script src="shared/LessonBoot.js"></script>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans+TC:wght@400;500;700&family=Noto+Serif+TC:wght@700;900&family=STIX+Two+Text:ital,wght@0,500;1,500&display=swap">
<link rel="stylesheet" href="shared/lesson.css">
</head>
<body>
<div class="wrap" id="ahs-vl-root" data-ahs-module="VisualLesson" data-ahs-subject="${spec.subject}" data-ahs-unit="${spec.unit}">
  <header class="top">
    <div class="eyebrow">${spec.eyebrow}</div>
    <h1>${spec.h1}<small>${spec.h1small}</small></h1>
    <div class="legend">
      ${(spec.legend || ["src", "add"]).map((t) => TAG[t]).join("\n      ")}
      <span class="prog" id="prog">已完成 0 / ${n}</span>
    </div>
  </header>

  <nav class="toc" aria-label="本頁目錄">
    ${spec.sections.map((s) => '<a href="#s' + s.id + '">' + s.id + " " + (s.short || s.title) + "</a>").join("")}
  </nav>
${sections}

  <footer class="foot">
    <h2>參考資料</h2>
    <ul>
${(spec.footer || []).map((li) => "      <li>" + li + "</li>").join("\n")}
    </ul>
  </footer>
</div>

<script src="shared/LessonRuntime.js"></script>
<script>
(function(){
'use strict';
${spec.script.trim()}
})();
</script>
</body>
</html>
`;
}

function specFiles(ids) {
  const dir = path.join(LESSONS, "src");
  const all = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.js$/.test(f)).map((f) => f.replace(/\.js$/, "")) : [];
  return ids && ids.length ? ids : all;
}

function run(ids, check) {
  const stale = [];
  specFiles(ids).forEach((id) => {
    const specPath = path.join(LESSONS, "src", id + ".js");
    delete require.cache[require.resolve(specPath)];
    const html = build(require(specPath));
    const out = path.join(LESSONS, id + ".html");
    const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
    if (cur !== html) { stale.push(id); if (!check) { fs.writeFileSync(out, html); } }
  });
  return stale;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const check = args.indexOf("--check") !== -1;
  const ids = args.filter((a) => a[0] !== "-");
  const stale = run(ids, check);
  if (check) { console.log(stale.length ? "STALE: " + stale.join(", ") : "BuildVisualLesson: up to date"); process.exit(stale.length ? 1 : 0); }
  console.log(stale.length ? "written: " + stale.join(", ") : "nothing changed");
}

module.exports = { build: build, run: run };
