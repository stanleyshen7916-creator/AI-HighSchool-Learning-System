/* js/runtime/TeachingMaterialContentLoader.js — queue 9.4 (T3). Loads one material's summary / questions on demand.

   js/data/materials-content/<id>.js (generated by docs/TeachingMaterials/scripts/TeachingMaterialSplit.js) registers
   the material's content in AHS.TeachingMaterialContentStore[<id>]. This module adds that file as a <script> tag when
   somebody asks for it — no fetch / XHR, so it works the same over file:// and on GitHub Pages — and resolves a Promise
   when the script has run. It is a loader only: no data of its own, nothing about what the content means.

     ensure(id)        -> Promise<{ summary, questions, variants? }>   (the same script is never added twice, also when
                                                                         several callers ask at once)
     ensureAll(ids)    -> Promise<{ [id]: content }>
     has(id), get(id)  -> synchronous: already loaded?  / the content or null
     setBase(path)     -> where the content files live (default "js/data/materials-content/")

   Not wired into any page yet: until the pages switch from TeachingMaterialData.js to TeachingMaterialIndex.js
   (queue 9.4 T5–T7) nothing calls it. */
window.AHS = window.AHS || {};
AHS.TeachingMaterialContentLoader = (function () {
  "use strict";

  var base = "js/data/materials-content/";
  var inFlight = {};

  function store() {
    AHS.TeachingMaterialContentStore = AHS.TeachingMaterialContentStore || {};
    return AHS.TeachingMaterialContentStore;
  }
  function validId(id) { return typeof id === "string" && /^tm_\d+$/.test(id); }
  function has(id) { return !!store()[id]; }
  function get(id) { return store()[id] || null; }
  function setBase(path) { base = String(path).replace(/\/*$/, "/"); }

  function ensure(id) {
    if (!validId(id)) { return Promise.reject(new Error("教材編號不正確：" + id)); }
    if (has(id)) { return Promise.resolve(get(id)); }
    if (inFlight[id]) { return inFlight[id]; }
    inFlight[id] = new Promise(function (resolve, reject) {
      var script = document.createElement("script");
      script.src = base + id + ".js";
      script.async = true;
      script.onload = function () {
        delete inFlight[id];
        if (has(id)) { resolve(get(id)); } else { reject(new Error("內容檔已載入但沒有註冊 " + id)); }
      };
      script.onerror = function () {
        delete inFlight[id];
        if (script.parentNode) { script.parentNode.removeChild(script); }   // so a later attempt (network back) can try again
        reject(new Error("載入教材內容失敗：" + id));
      };
      (document.head || document.documentElement).appendChild(script);
    });
    return inFlight[id];
  }

  function ensureAll(ids) {
    var list = Array.isArray(ids) ? ids : [];
    return Promise.all(list.map(ensure)).then(function (contents) {
      var out = {};
      list.forEach(function (id, i) { out[id] = contents[i]; });
      return out;
    });
  }

  return { ensure: ensure, ensureAll: ensureAll, has: has, get: get, setBase: setBase };
})();
